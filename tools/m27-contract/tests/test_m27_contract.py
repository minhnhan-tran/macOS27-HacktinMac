class Release(unittest.TestCase):
    def setUp(self):
        self.d = Path(tempfile.mkdtemp())
        (self.d / 'libm27.dylib').write_bytes(b'lib')
        self.r = {
            'contract_version': 2, 'release': '27.2.1-26B131.0', 'prerelease': True, 'proven_models': ['MacBookPro9,2'],
            'version': 'v0.1.0', 'channel': 'dev', 'state': 'incomplete',
            'assembly': 'mbp92-26B131', 'golden_build': '26B131', 'donor_build': '25G342', 'oclp': 'a' * 7,
            'm27_patcher': 'b' * 7, 'm27_runtime': 'c' * 7,
            'downloads': [{'row': 'kdk', 'name': 'KDK.dmg', 'url': 'https://example.invalid/KDK.dmg', 'size': 1,
                           'sha256': '1' * 64}],
            'assets': [{'row': 'm27_runtime', 'file': 'libm27.dylib', 'url': C['URL_PREFIX'] + '/27.2.1-26B131.0/libm27.dylib',
                        'size': 3, 'sha256': sha(b'lib'), 'commit': 'c' * 7, 'format': 'file'}],
            'made_on_mac': [{'row': 'tahoe_boot_donors', 'producer': 'tools/donors', 'inputs': ['kdk']}],
            'harvested': ['icon_caches'], 'expected': {'image': '2' * 64}}

    def check(self, stage=True):
        (self.d / 'release.json').write_text(json.dumps(self.r))
        return C['check_release_file'](self.d / 'release.json', self.d if stage else None)

    def test_good_release_and_stage(self):
        self.assertEqual(self.check(), [])

    def test_seeded_violations(self):
        a = self.r['assets'][0]
        a['url'] = C['URL_PREFIX'] + '/27.2.1-26B131.1/libm27.dylib'               # another tag
        del self.r['downloads'][0]['sha256']                                         # unpinned download
        self.r['made_on_mac'].append({'row': 'm27_runtime', 'producer': ''})          # both, and no producer
        self.r['harvested'].append('tahoe_boot_donors')
        (self.d / 'stray.bin').write_bytes(b'x')
        bad = '\n'.join(self.check())
        for want in ('asset m27_runtime url', 'download kdk lacks sha256', 'made_on_mac m27_runtime names no producer',
                     'row m27_runtime is in assets and made_on_mac', 'row tahoe_boot_donors is in made_on_mac and harvested',
                     'stray.bin is staged but not an asset'):
            self.assertIn(want, bad)

    def test_profiles_name_their_rows(self):
        self.r['profiles'] = {'alpha-v0.1.0': {'assembly': 'mbp92-26B131', 'target': 'mbp92', 'patch_set': 'alpha-v0.1.0',
                                               'rows': ['kdk', 'm27_runtime', 'tahoe_boot_donors']},
                              'generic': {'assembly': 'generic-26B131', 'target': 'generic', 'patch_set': 'generic',
                                          'rows': ['kdk', 'm27_runtime']}}
        self.assertEqual(self.check(), [])
        self.r['profiles']['generic']['rows'].append('nothing')
        self.r['profiles']['alpha-v0.1.0']['rows'].remove('tahoe_boot_donors')
        self.r['assets'][0]['harvested'] = True
        self.r['target'] = 'mbp92'
        self.r['assembly'] = 'other'
        bad = '\n'.join(self.check())
        for want in ('profile generic names row nothing', 'row tahoe_boot_donors belongs to no profile',
                     'profile generic (target generic) uses harvested asset m27_runtime',
                     'assembly other is none of the profiles'):
            self.assertIn(want, bad)

    def test_an_asset_without_a_public_commit_stands_on_its_sha256(self):
        a = self.r['assets'][0]
        a['commit'] = ''
        self.assertEqual(self.check(), [])                     # no repo, commit "": published by sha256 alone
        a['repo'] = 'm27-patcher'
        self.assertIn('asset m27_runtime lacks commit', '\n'.join(self.check()))   # a named repo needs its commit

    def test_an_asset_hosted_by_m27_runtime_is_staged_apart(self):
        a = self.r['assets'][0]
        a['url'] = 'https://github.com/minhnhan-tran/macOS27-HacktinMac/releases/download/runtime-v0.1.0-alpha.1/libm27.dylib'
        bad = '\n'.join(self.check())
        self.assertIn('libm27.dylib is staged but not an asset', bad)   # in the upload folder: refused
        (self.d / 'external').mkdir()
        (self.d / 'libm27.dylib').rename(self.d / 'external' / 'libm27.dylib')   # hosted elsewhere: staged apart
        self.assertEqual(self.check(), [])
        a['url'] = 'https://example.invalid/libm27.dylib'
        self.assertIn('asset m27_runtime url', '\n'.join(self.check()))

    def test_harvested_asset_only_for_an_allowed_target(self):
        (self.d / 'icon_caches.tar').write_bytes(b'tar')
        self.r['harvested'].remove('icon_caches')
        self.r['assets'].append({'row': 'icon_caches', 'file': 'icon_caches.tar', 'harvested': True,
                                 'url': C['URL_PREFIX'] + '/27.2.1-26B131.0/icon_caches.tar', 'size': 3,
                                 'sha256': sha(b'tar'), 'commit': 'd' * 7, 'format': 'tar'})
        self.r['target'] = 'mbp92'
        self.assertEqual(self.check(), [])
        self.r['target'] = 'mbp121'
        self.assertIn('target mbp121 may not ship harvested rows', '\n'.join(self.check()))
        del self.r['target']
        self.assertIn('target None may not ship harvested rows', '\n'.join(self.check()))
        self.r['target'] = 'mbp92'
        self.r['harvested'].append('icon_caches')                     # shipped and listed as not shipped
        self.assertIn('row icon_caches is in assets and harvested', '\n'.join(self.check()))

    def test_staged_file_must_match(self):
        (self.d / 'libm27.dylib').write_bytes(b'LIB')
        self.assertEqual(self.check(), ['release: staged libm27.dylib does not match its sha256'])
        self.assertEqual(self.check(stage=False), [])
        (self.d / 'libm27.dylib').unlink()
        self.assertIn('is not staged', self.check()[0])

    def test_name_and_version(self):
        self.r['release'] = 'v0.1.0'
        self.r['contract_version'] = 1
        self.r['version'] = '0.1.0'
        bad = '\n'.join(self.check(stage=False))
        self.assertIn("name 'v0.1.0' is not MACOS-BUILD.N", bad)
        self.assertIn('contract_version 1', bad)
        self.assertIn("version '0.1.0' is not vX.Y.Z", bad)

    def test_channels(self):
        self.assertEqual(self.check(), [])                               # dev may be incomplete
        self.r['channel'] = 'beta'
        self.assertIn("a beta release must be complete (state 'incomplete')", '\n'.join(self.check()))
        self.r['state'] = 'complete'
        self.assertEqual(self.check(), [])
        self.r['prerelease'] = False
        self.assertIn('a beta release is a prerelease', '\n'.join(self.check()))
        self.r['prerelease'], self.r['channel'] = True, 'nightly'
        self.assertIn("channel 'nightly' is not one of dev, alpha, beta", '\n'.join(self.check()))
        del self.r['channel']
        self.assertEqual(self.check(), ['release: lacks channel'])


class Schemas(unittest.TestCase):
    """The published schemas name the same fields and kinds the checker enforces."""
    ROOT = Path(__file__).resolve().parents[1] / 'schemas'

    def load(self, name):
        return json.loads((self.ROOT / name).read_text())

    def test_contract_kinds(self):
        s = self.load('contract.schema.json')
        kinds = {c['properties']['kind']['const'] for c in s['properties']['checks']['items']['oneOf']}
        self.assertEqual(kinds, set(C['CHECKS']))
        self.assertEqual(s['properties']['contract_version']['const'], C['CONTRACT_VERSION'])

    def test_generated_lock_fields(self):
        item = self.load('generated-lock.schema.json')['properties']['files']['items']
        self.assertEqual(tuple(item['required']), C['LOCK_FIELDS'])
        self.assertEqual(item['properties']['input_kind']['enum'], list(C['INPUT_KINDS']))
        per_kind = {r['if']['properties']['input_kind']['const']: tuple(r['then']['required']) for r in item['allOf']}
        self.assertEqual(per_kind, C['INPUT_KINDS'])

    def test_release_fields(self):
        s = self.load('release.schema.json')
        self.assertEqual(tuple(s['required']), C['RELEASE_FIELDS'])
        items = {k: s['properties'][k]['items'] for k in ('downloads', 'assets')}
        self.assertEqual(tuple(items['downloads']['required']), C['DOWNLOAD_FIELDS'])
        self.assertEqual(tuple(items['assets']['required']), C['ASSET_FIELDS'])
        self.assertEqual(tuple(items['assets']['properties']['format']['enum']), C['ASSET_FORMATS'])
        self.assertTrue(C['RELEASE_NAME'].match('27.2.1-26B131.0'))

    def test_payload_fields(self):
        self.assertEqual(tuple(self.load('payload-manifest.schema.json')['required']), C['PAYLOAD_FIELDS'])


